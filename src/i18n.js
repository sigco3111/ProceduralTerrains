// 일부 키가 {변수} 패턴을 가질 때 보간
export function tf(key, vars) {
  let s = t(key);
  if (vars && typeof vars === 'object') {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split('{' + k + '}').join(String(v));
    }
  }
  return s;
}

